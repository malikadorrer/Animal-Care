-- Animal Care shop database (PostgreSQL)
-- Run once against an empty development database, then load seed.sql.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           text NOT NULL UNIQUE,
    password_hash   text NOT NULL,
    full_name       text NOT NULL,
    phone           text,
    role            text NOT NULL DEFAULT 'customer'
                    CHECK (role IN ('customer', 'admin')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT users_email_nonempty CHECK (length(trim(email)) > 0),
    CONSTRAINT users_full_name_nonempty CHECK (length(trim(full_name)) > 0)
);

CREATE TABLE IF NOT EXISTS pets (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name            text NOT NULL,
    species         text NOT NULL CHECK (species IN ('dog', 'cat')),
    breed           text,
    birth_date      date,
    sex             text CHECK (sex IN ('female', 'male', 'unknown')),
    weight_kg       numeric(6, 2) CHECK (weight_kg IS NULL OR weight_kg > 0),
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pets_name_nonempty CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS categories (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_category_id  bigint REFERENCES categories(id) ON DELETE SET NULL,
    name                text NOT NULL,
    slug                text NOT NULL UNIQUE,
    description         text,
    is_active           boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT categories_name_nonempty CHECK (length(trim(name)) > 0),
    CONSTRAINT categories_slug_nonempty CHECK (length(trim(slug)) > 0),
    CONSTRAINT categories_not_own_parent CHECK (parent_category_id IS NULL OR parent_category_id <> id)
);

CREATE TABLE IF NOT EXISTS products (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id         bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    sku                 text NOT NULL UNIQUE,
    slug                text NOT NULL UNIQUE,
    name                text NOT NULL,
    description         text,
    price               numeric(10, 2) NOT NULL CHECK (price > 0),
    stock_quantity      integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    target_species      text NOT NULL DEFAULT 'all'
                        CHECK (target_species IN ('dog', 'cat', 'all')),
    min_age_months      integer NOT NULL DEFAULT 0 CHECK (min_age_months >= 0),
    max_age_months      integer CHECK (max_age_months IS NULL OR max_age_months >= min_age_months),
    image_url           text,
    is_active           boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT products_sku_nonempty CHECK (length(trim(sku)) > 0),
    CONSTRAINT products_slug_nonempty CHECK (length(trim(slug)) > 0),
    CONSTRAINT products_name_nonempty CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS cart (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status          text NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active', 'converted', 'abandoned')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cart_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id         bigint NOT NULL REFERENCES cart(id) ON DELETE CASCADE,
    product_id      bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity        integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
    added_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cart_items_one_product_per_cart UNIQUE (cart_id, product_id)
);

CREATE TABLE IF NOT EXISTS orders (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    cart_id             bigint UNIQUE REFERENCES cart(id) ON DELETE SET NULL,
    recipient_name      text NOT NULL,
    recipient_phone     text NOT NULL,
    shipping_address    text NOT NULL,
    status              text NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
    total_amount        numeric(12, 2) NOT NULL CHECK (total_amount >= 0),
    customer_note       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT orders_recipient_name_nonempty CHECK (length(trim(recipient_name)) > 0),
    CONSTRAINT orders_recipient_phone_nonempty CHECK (length(trim(recipient_phone)) > 0),
    CONSTRAINT orders_shipping_address_nonempty CHECK (length(trim(shipping_address)) > 0)
);

CREATE TABLE IF NOT EXISTS order_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id      bigint REFERENCES products(id) ON DELETE SET NULL,
    product_name    text NOT NULL,
    sku             text,
    unit_price      numeric(10, 2) NOT NULL CHECK (unit_price > 0),
    quantity        integer NOT NULL CHECK (quantity > 0),
    line_total      numeric(12, 2) GENERATED ALWAYS AS (unit_price * quantity) STORED,
    CONSTRAINT order_items_product_name_nonempty CHECK (length(trim(product_name)) > 0)
);

CREATE TABLE IF NOT EXISTS favorites (
    user_id         bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id      bigint NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, product_id)
);

CREATE TABLE IF NOT EXISTS reviews (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id      bigint NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    rating          smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title           text,
    body            text,
    is_published    boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT reviews_one_per_user_product UNIQUE (user_id, product_id),
    CONSTRAINT reviews_title_or_body CHECK (
        (title IS NULL OR length(trim(title)) > 0)
        AND (body IS NULL OR length(trim(body)) > 0)
    )
);

CREATE INDEX IF NOT EXISTS pets_user_id_idx ON pets(user_id);
CREATE INDEX IF NOT EXISTS categories_parent_category_id_idx ON categories(parent_category_id);
CREATE INDEX IF NOT EXISTS products_category_active_idx ON products(category_id, is_active);
CREATE INDEX IF NOT EXISTS products_species_age_idx
    ON products(target_species, min_age_months, max_age_months) WHERE is_active;
CREATE UNIQUE INDEX IF NOT EXISTS cart_one_active_per_user_idx ON cart(user_id) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS cart_items_product_id_idx ON cart_items(product_id);
CREATE INDEX IF NOT EXISTS orders_user_created_at_idx ON orders(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS orders_status_created_at_idx ON orders(status, created_at DESC);
CREATE INDEX IF NOT EXISTS order_items_product_id_idx ON order_items(product_id);
CREATE INDEX IF NOT EXISTS favorites_product_id_idx ON favorites(product_id);
CREATE INDEX IF NOT EXISTS reviews_product_published_idx ON reviews(product_id, is_published);

COMMIT;
